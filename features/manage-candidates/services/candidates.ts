import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query"
import { z } from "zod"

import { api } from "@/lib/axios"

import { resource } from "@/lib/resource"
import { email, requiredDate, requiredText } from "@/lib/validation"

// Shape from GET /admin/candidates. Dates are calendar days ("1995-04-21").
export type Candidate = {
  id: string
  certificateId: string
  // Null for a request made on the website, until the admin issues the certificate.
  certificateNo: string | null
  passportName: string
  passportNo: string
  dateOfBirth: string
  address: string
  email: string
  course: { id: string; title: string }
  issueDate: string | null
  nationality: string
  isVerified: boolean
  verifiedAt: string | null
  createdAt: string
  updatedAt: string
}

export const adminCandidates = resource<Candidate, CandidatePayload>(
  "admin/candidates"
)

// Under the list's key, so saving or deleting refreshes it too.
export const useCandidate = (id: string) =>
  useQuery({
    queryKey: [...adminCandidates.key, id],
    queryFn: async () =>
      (await api.get<{ data: Candidate }>(`/admin/candidates/${id}`)).data.data,
  })

// Marks a candidate verified; the candidate lists (verified and not) refresh.
export const useVerifyCandidate = () => {
  const qc = useQueryClient()
  return useMutation({
    mutationFn: async (id: string) =>
      (await api.post<{ data: Candidate }>(`/admin/candidates/${id}/verify`))
        .data.data,
    onSuccess: () => qc.invalidateQueries({ queryKey: adminCandidates.key }),
  })
}

// Today as YYYY-MM-DD in the viewer's zone, the same way <input type="date"> counts days.
export const today = () => new Date().toLocaleDateString("en-CA")

// Every field is required; the certificate ID is generated by the API.
export const candidateSchema = z.object({
  certificateNo: requiredText(60),
  passportName: requiredText(160),
  passportNo: requiredText(40),
  dateOfBirth: requiredDate.refine((d) => d < today(), {
    message: "The date of birth must be in the past",
  }),
  address: requiredText(500),
  email: email.pipe(z.string().max(254, "This is too long")),
  courseId: z.string().min(1, "Choose a course"),
  issueDate: requiredDate,
  nationality: requiredText(80),
})

export type CandidateForm = z.input<typeof candidateSchema>
export type CandidatePayload = z.output<typeof candidateSchema>

export const toCandidateForm = (c?: Candidate): CandidateForm => ({
  certificateNo: c?.certificateNo ?? "",
  passportName: c?.passportName ?? "",
  passportNo: c?.passportNo ?? "",
  dateOfBirth: c?.dateOfBirth ?? "",
  address: c?.address ?? "",
  email: c?.email ?? "",
  courseId: c?.course.id ?? "",
  issueDate: c?.issueDate ?? today(),
  nationality: c?.nationality ?? "",
})

// A candidate's student login. password is null once the student sets their own.
export type CandidateLogin = {
  hasAccount: boolean
  username: string | null
  password: string | null
  passwordChangedByStudent: boolean
}

const loginKey = (id: string) => [...adminCandidates.key, id, "login"]

export const useCandidateLogin = (id: string) =>
  useQuery({
    queryKey: loginKey(id),
    queryFn: async () =>
      (await api.get<{ data: CandidateLogin }>(`/admin/candidates/${id}/login`))
        .data.data,
    // Don't keep the password cached.
    staleTime: 0,
    gcTime: 0,
  })

// Omit the password to generate one.
export const useSetLoginPassword = (id: string) => {
  const qc = useQueryClient()
  return useMutation({
    mutationFn: async (password?: string) =>
      (
        await api.put<{ data: CandidateLogin }>(
          `/admin/candidates/${id}/login/password`,
          password ? { password } : {}
        )
      ).data.data,
    onSuccess: (login) => qc.setQueryData(loginKey(id), login),
  })
}

// The course they requested, the courses on their orders, and anything their login can open.
export type CandidateCourse = {
  id: string
  title: string
  granted: boolean
  grantedAt: string | null
}
export type CandidateCourses = {
  hasAccount: boolean
  courses: CandidateCourse[]
}

const coursesKey = (id: string) => [...adminCandidates.key, id, "courses"]

export const useCandidateCourses = (id: string) =>
  useQuery({
    queryKey: coursesKey(id),
    queryFn: async () =>
      (
        await api.get<{ data: CandidateCourses }>(
          `/admin/candidates/${id}/courses`
        )
      ).data.data,
    // Orders and the login tab change it too; refetch whenever the tab opens.
    staleTime: 0,
  })

// Grant unlocks the course and emails the student; revoke locks it.
export const useSetCourseAccess = (id: string) => {
  const qc = useQueryClient()
  return useMutation({
    mutationFn: async ({
      courseId,
      grant,
    }: {
      courseId: string
      grant: boolean
    }) =>
      (
        await api.request<{ data: CandidateCourses }>({
          method: grant ? "POST" : "DELETE",
          url: `/admin/candidates/${id}/courses/${courseId}/access`,
        })
      ).data.data,
    onSuccess: (courses) => qc.setQueryData(coursesKey(id), courses),
  })
}

// For a candidate with no login. The email is sent only when asked.
export const useCreateLogin = (id: string) => {
  const qc = useQueryClient()
  return useMutation({
    mutationFn: async (sendEmail: boolean) =>
      (
        await api.post<{ data: CandidateLogin }>(
          `/admin/candidates/${id}/login`,
          { sendEmail }
        )
      ).data.data,
    onSuccess: (login) => qc.setQueryData(loginKey(id), login),
  })
}

// Generated PDFs: the certificate and the transcript, each in a digital (cream, for screens and
// email) and a print (white, for paper) version. Built from the record on every download.
export type CertificateDocument = "certificate" | "transcript"
export type CertificateVariant = "digital" | "print"

// The API has templates for TEFL and TESOL courses.
export const hasCertificateTemplate = (courseTitle: string) =>
  /\b(TEFL|TESOL)\b/i.test(courseTitle)

// Fetches through the API client (it carries the access token). The API builds the PDF from the
// record each time.
async function fetchCertificateDocument(
  id: string,
  document: CertificateDocument,
  variant: CertificateVariant
) {
  const res = await api.get<Blob>(
    `/admin/candidates/${id}/documents/${document}/${variant}`,
    { responseType: "blob" }
  )
  return toPdfFile(res, `${document}-${variant}.pdf`)
}

// A PDF response as a typed Blob plus the filename the API chose.
export function toPdfFile(
  res: { data: Blob; headers: Record<string, unknown> },
  fallbackName: string
) {
  const header = String(res.headers["content-disposition"] ?? "")
  return {
    blob: new Blob([res.data], { type: "application/pdf" }),
    filename: /filename="([^"]+)"/.exec(header)?.[1] ?? fallbackName,
  }
}

export const useDownloadCertificateDocument = (id: string) =>
  useMutation({
    mutationFn: async ({
      document,
      variant,
    }: {
      document: CertificateDocument
      variant: CertificateVariant
    }) => {
      const { blob, filename } = await fetchCertificateDocument(
        id,
        document,
        variant
      )
      saveBlob(blob, filename)
    },
  })

// For viewing in the portal: the PDF plus an object URL to show it. Under the candidate's key, so
// editing the record refetches it; not kept once the viewer closes. The viewer revokes the URL.
export const useCertificateDocument = (
  id: string,
  document: CertificateDocument,
  variant: CertificateVariant,
  enabled: boolean
) =>
  useQuery({
    queryKey: [...adminCandidates.key, id, "documents", document, variant],
    queryFn: async () => {
      const file = await fetchCertificateDocument(id, document, variant)
      return { ...file, url: URL.createObjectURL(file.blob) }
    },
    enabled,
    gcTime: 0,
  })

export function saveBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob)
  const link = Object.assign(window.document.createElement("a"), {
    href: url,
    download: filename,
  })
  window.document.body.append(link)
  link.click()
  link.remove()
  // Give the browser a moment to start the download before the URL goes away.
  setTimeout(() => URL.revokeObjectURL(url), 10_000)
}
