import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query"
import { z } from "zod"

import { api } from "@/lib/axios"

import { resource } from "@/lib/resource"
import { email, requiredDate, requiredText } from "@/lib/validation"

// Shape from GET /admin/candidates. Dates are calendar days ("1995-04-21").
export type Candidate = {
  id: string
  certificateId: string
  // Null for a request made on the website, until the admin issues the certificate.
  certificateNo: string | null
  passportName: string
  passportNo: string
  dateOfBirth: string
  address: string
  email: string
  course: { id: string; title: string }
  issueDate: string | null
  nationality: string
  isVerified: boolean
  verifiedAt: string | null
  createdAt: string
  updatedAt: string
}

export const adminCandidates = resource<Candidate, CandidatePayload>(
  "admin/candidates"
)

// Under the list's key, so saving or deleting refreshes it too.
export const useCandidate = (id: string) =>
  useQuery({
    queryKey: [...adminCandidates.key, id],
    queryFn: async () =>
      (await api.get<{ data: Candidate }>(`/admin/candidates/${id}`)).data.data,
  })

// Marks a candidate verified; the candidate lists (verified and not) refresh.
export const useVerifyCandidate = () => {
  const qc = useQueryClient()
  return useMutation({
    mutationFn: async (id: string) =>
      (await api.post<{ data: Candidate }>(`/admin/candidates/${id}/verify`))
        .data.data,
    onSuccess: () => qc.invalidateQueries({ queryKey: adminCandidates.key }),
  })
}

// Today as YYYY-MM-DD in the viewer's zone, the same way <input type="date"> counts days.
export const today = () => new Date().toLocaleDateString("en-CA")

// Every field is required; the certificate ID is generated by the API.
export const candidateSchema = z.object({
  certificateNo: requiredText(60),
  passportName: requiredText(160),
  passportNo: requiredText(40),
  dateOfBirth: requiredDate.refine((d) => d < today(), {
    message: "The date of birth must be in the past",
  }),
  address: requiredText(500),
  email: email.pipe(z.string().max(254, "This is too long")),
  courseId: z.string().min(1, "Choose a course"),
  issueDate: requiredDate,
  nationality: requiredText(80),
})

export type CandidateForm = z.input<typeof candidateSchema>
export type CandidatePayload = z.output<typeof candidateSchema>

export const toCandidateForm = (c?: Candidate): CandidateForm => ({
  certificateNo: c?.certificateNo ?? "",
  passportName: c?.passportName ?? "",
  passportNo: c?.passportNo ?? "",
  dateOfBirth: c?.dateOfBirth ?? "",
  address: c?.address ?? "",
  email: c?.email ?? "",
  courseId: c?.course.id ?? "",
  issueDate: c?.issueDate ?? today(),
  nationality: c?.nationality ?? "",
})

// A candidate's student login. password is null once the student sets their own.
export type CandidateLogin = {
  hasAccount: boolean
  username: string | null
  password: string | null
  passwordChangedByStudent: boolean
  // Whether an admin granted access to the course.
  enrolled: boolean
}

const loginKey = (id: string) => [...adminCandidates.key, id, "login"]

export const useCandidateLogin = (id: string) =>
  useQuery({
    queryKey: loginKey(id),
    queryFn: async () =>
      (await api.get<{ data: CandidateLogin }>(`/admin/candidates/${id}/login`))
        .data.data,
    // Don't keep the password cached.
    staleTime: 0,
    gcTime: 0,
  })

// Omit the password to generate one.
export const useSetLoginPassword = (id: string) => {
  const qc = useQueryClient()
  return useMutation({
    mutationFn: async (password?: string) =>
      (
        await api.put<{ data: CandidateLogin }>(
          `/admin/candidates/${id}/login/password`,
          password ? { password } : {}
        )
      ).data.data,
    onSuccess: (login) => qc.setQueryData(loginKey(id), login),
  })
}

// Grant unlocks the course and emails the student; revoke locks it.
export const useSetCourseAccess = (id: string) => {
  const qc = useQueryClient()
  return useMutation({
    mutationFn: async (grant: boolean) =>
      (
        await api.request<{ data: CandidateLogin }>({
          method: grant ? "POST" : "DELETE",
          url: `/admin/candidates/${id}/access`,
        })
      ).data.data,
    onSuccess: (login) => qc.setQueryData(loginKey(id), login),
  })
}

// For a candidate with no login. The email is sent only when asked.
export const useCreateLogin = (id: string) => {
  const qc = useQueryClient()
  return useMutation({
    mutationFn: async (sendEmail: boolean) =>
      (
        await api.post<{ data: CandidateLogin }>(
          `/admin/candidates/${id}/login`,
          { sendEmail }
        )
      ).data.data,
    onSuccess: (login) => qc.setQueryData(loginKey(id), login),
  })
}
